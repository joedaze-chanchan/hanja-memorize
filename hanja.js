// HANJA[한자] = { ch, hun, eum, word, wordKo, level, strokes }
export const HANJA = {};
export const HANJA_ORDER = [];
for (const [level, list] of Object.entries(RAW)) {
  for (const [ch, hun, eum, word, wordKo] of list) {
    HANJA[ch] = { ch, hun, eum, word, wordKo, level, strokes: STROKES[ch] || [] };
    HANJA_ORDER.push(ch);
  }
}

export function listByLevel(level) {
  return HANJA_ORDER.filter((ch) => level === "all" || HANJA[ch].level === level);
}

// "학교 교" 같은 훈음 표기
export function hunEum(ch) {
  const h = HANJA[ch];
  return `${h.hun} ${h.eum}`;
}

// 한자 한 글자의 코드 (발음 파일 이름에 쓴다). 예: 校 → "6821"
export function codeOf(ch) {
  return ch.codePointAt(0).toString(16);
}
